const mongoose = require('mongoose');

const orderItemSchema = new mongoose.Schema({
  product: { type: mongoose.Schema.Types.ObjectId, ref: 'Product', required: true },
  name: { type: String, required: true },
  price: { type: Number, required: true },
  quantity: { type: Number, required: true, min: 1 },
  image: { type: String, default: '' },
  variant: { type: String, default: '' },
  seller: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
  sellerName: { type: String, default: 'VEXIVO Official' },
});

const orderSchema = new mongoose.Schema(
  {
    orderNumber: { type: String, required: true, unique: true },
    user: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    guestEmail: { type: String, default: '' },
    items: [orderItemSchema],
    subtotal: { type: Number, required: true },
    discount: { type: Number, default: 0 },
    shipping: { type: Number, default: 0 },
    tax: { type: Number, default: 0 },
    total: { type: Number, required: true },
    coupon: { type: String, default: '' },
    shippingAddress: {
      firstName: { type: String, required: true },
      lastName: { type: String, default: '' },
      address: { type: String, required: true },
      city: { type: String, required: true },
      state: { type: String, default: '' },
      postalCode: { type: String, required: true },
      country: { type: String, default: 'India' },
      phone: { type: String, default: '' },
    },
    billingAddress: {
      firstName: { type: String, default: '' },
      lastName: { type: String, default: '' },
      address: { type: String, default: '' },
      city: { type: String, default: '' },
      state: { type: String, default: '' },
      postalCode: { type: String, default: '' },
      country: { type: String, default: 'India' },
    },
    paymentMethod: { type: String, default: 'Credit Card' },
    paymentStatus: {
      type: String,
      enum: ['pending', 'paid', 'failed', 'refunded'],
      default: 'pending',
    },
    paymentDetails: {
      transactionId: { type: String, default: '' },
      utrNumber: { type: String, default: '' },
      cardLast4: { type: String, default: '' },
      cardBrand: { type: String, default: '' },
      verifiedAt: { type: Date, default: null },
      verifiedBy: { type: String, default: '' },
      gateway: { type: String, default: '' },
    },
    orderStatus: {
      type: String,
      enum: [
        'pending',
        'confirmed',
        'processing',
        'ready_for_pickup',
        'picked_up',
        'warehouse_received',
        'scanned',
        'sorted',
        'dispatched_from_warehouse',
        'hub_received',
        'ready_for_delivery',
        'shipped',
        'delivery_partner_assigned',
        'out_for_delivery',
        'delivery_attempted',
        'rescheduled',
        'delivered',
        'cancelled',
        'returned',
        'return_initiated',
        'return_in_transit',
        'return_to_seller',
        'exchange_requested',
      ],
      default: 'processing',
    },
    cancellationReason: { type: String, default: '' },
    cancelledAt: { type: Date, default: null },
    returnReason: { type: String, default: '' },
    returnedAt: { type: Date, default: null },
    trackingNumber: { type: String, default: '' },
    shipment: { type: mongoose.Schema.Types.ObjectId, ref: 'Shipment' },
    deliveryPartner: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    deliveryPartnerName: { type: String, default: '' },
    deliveryPartnerPhone: { type: String, default: '' },
    deliveryDetails: {
      pickupOtp: { type: String, default: '' },
      deliveryOtp: { type: String, default: '' },
      deliveryStatus: {
        type: String,
        enum: [
          'unassigned',
          'pending_pickup',
          'picked_up',
          'at_warehouse',
          'sorted',
          'in_transit_to_hub',
          'at_hub',
          'ready_for_delivery',
          'assigned',
          'accepted',
          'reached_pickup',
          'picked_up_from_hub',
          'out_for_delivery',
          'reached_customer',
          'delivered',
          'failed',
          'rescheduled',
          'return_to_seller',
        ],
        default: 'unassigned',
      },
      assignedAt: { type: Date, default: null },
      acceptedAt: { type: Date, default: null },
      reachedPickupAt: { type: Date, default: null },
      pickedUpAt: { type: Date, default: null },
      outForDeliveryAt: { type: Date, default: null },
      reachedCustomerAt: { type: Date, default: null },
      deliveredAt: { type: Date, default: null },
      failureReason: { type: String, default: '' },
      rescheduledDate: { type: Date, default: null },
      notes: { type: String, default: '' },
      codAmountCollected: { type: Number, default: 0 },
      codCollectedAt: { type: Date, default: null },
      codReconciled: { type: Boolean, default: false },
      codSettledAt: { type: Date, default: null },
      codSettledBy: { type: String, default: '' },
      estimatedDistanceKm: { type: Number, default: 0 },
      weatherSurgeApplied: { type: Boolean, default: false },
    },
    returnDetails: {
      status: {
        type: String,
        enum: [
          'none',
          'requested',
          'approved',
          'rejected',
          'pickup_assigned',
          'picked_up',
          'completed',
          'refunded',
        ],
        default: 'none',
      },
      reason: { type: String, default: '' },
      evidence: [{ type: String }],
      refundMethod: { type: String, default: 'Original Payment Method' },
      refundStatus: {
        type: String,
        enum: ['none', 'pending', 'processing', 'completed'],
        default: 'none',
      },
      returnPickupOtp: { type: String, default: '' },
      returnDeliveryPartner: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
      requestedAt: { type: Date, default: null },
      resolvedAt: { type: Date, default: null },
    },
    trackingHistory: [
      {
        status: { type: String, required: true },
        message: { type: String, required: true },
        timestamp: { type: Date, default: Date.now },
      },
    ],
  },
  { timestamps: true }
);

module.exports = mongoose.models.Order || mongoose.model('Order', orderSchema);
